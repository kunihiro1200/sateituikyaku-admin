/**
 * 営業会議「他決数推移」の元データ（Googleスプレッドシート「他決数推移」を移植）
 *
 * ■ 移植方針
 * - 元シートは 2022〜2026 の5つの年ブロックが横に並ぶ構造。ここでは「年 → 1〜12月の配列」に正規化した。
 * - 元シートにあった 合計 / 平均 / 前年比 / 各種比率（○○比・○○率）のセルは **取り込まず、画面側で集計しなおす**。
 *   （元シートは #DIV/0! や 320%、マイナス％など計算が壊れたセルが混在していたため）
 * - 元シートの「非表示」マーカー行・グレーの作業用セルは移植対象外。
 * - 値が無い月は null（元シートの空欄・「-」）。0 は「実績0件」としてそのまま保持。
 *
 * ■ 元シートの既知の不整合（画面にも注記を表示している）
 * - 種別（マ/戸/土）の合計と「他決（訪問済み）」行の合計が一致しない年がある。
 * - 追客電話の2023年は1〜4月しか値が無い（元シートの合計は別集計由来）。
 * - 2026年10〜12月は未到来のため0が入っている（平均は実績月だけで計算する）。
 */

export type YearKey = '2022' | '2023' | '2024' | '2025' | '2026';

export const YEARS: YearKey[] = ['2022', '2023', '2024', '2025', '2026'];

export const MONTH_LABELS = [
  '1月', '2月', '3月', '4月', '5月', '6月',
  '7月', '8月', '9月', '10月', '11月', '12月',
];

type V = number | null;
/** 1〜12月の12個ちょうど（TypeScriptの型で個数を強制する） */
export type Twelve = [V, V, V, V, V, V, V, V, V, V, V, V];

const _: V = null;
const m = (...v: Twelve): Twelve => v;

/** 実数行（元シートの値をそのまま保持する行） */
export type BaseRow = {
  key: string;
  label: string;
  note?: string;
  /** count: 件数（既定） / percent: 元シートが％入力で再計算できない行 */
  unit?: 'count' | 'percent';
  values: Partial<Record<YearKey, Twelve>>;
};

/** 集計行（他の行から計算する行） */
export type DerivedRow =
  | {
      key: string;
      label: string;
      note?: string;
      kind: 'sum';
      /** 足す行 */
      parts: string[];
      /** 引く行 */
      minus?: string[];
    }
  | {
      key: string;
      label: string;
      note?: string;
      kind: 'ratio';
      /** 分子の行 */
      num: string;
      /** 分母 = plus の合計 − minus の合計 */
      plus: string[];
      minus?: string[];
    };

export type TrendRow = BaseRow | DerivedRow;

export const isDerived = (r: TrendRow): r is DerivedRow => 'kind' in r;

export type TrendGroup = {
  id: string;
  title: string;
  note?: string;
  rows: TrendRow[];
};

