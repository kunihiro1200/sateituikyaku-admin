-- Migration 140: 買主の希望条件に「エリア（自由入力）」カラムを追加
--
-- 背景:
--   売主のマッチング欄には既存エリアコード配列（match_areas）とは別に
--   自由入力欄（match_area_free_text）があり、既存エリアマッピングに無い地名
--   （例: 「大分市寿町」）を入力できるが、買主の希望条件ページの「★エリア」
--   （desired_area）は既存エリアコードの複数選択のみで、自由入力欄が無かった。
--
--   そのため、買主が既存エリアコードに対応しない細かい地名で希望を伝えたい場合
--   （例: 「大分市寿町」）に入力する手段がなく、売主の自由入力（物件住所との
--   部分一致判定）と組み合わせたマッチングができなかった。
--
-- 用途:
--   買主希望条件ページの「★エリア」の下に自由入力欄を追加し、
--   売主のmatch_area_free_textと同様に、相手側の物件住所や自由入力との
--   部分一致でマッチング判定に使う。

ALTER TABLE buyers ADD COLUMN IF NOT EXISTS desired_area_free_text TEXT;

COMMENT ON COLUMN buyers.desired_area_free_text IS '希望エリア（自由入力・既存エリアマッピングに無い地名）。マッチング判定で相手の物件住所・自由入力との部分一致に使用';
